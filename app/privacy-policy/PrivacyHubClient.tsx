export default function PrivacyHubClient() {
  const containerRef = useRef<HTMLDivElement>(null);
  const [activeTabIdx, setActiveTabIdx] = useState(0);
  const [searchQuery, setSearchQuery] = useState("");
  const isTransitioningRef = useRef(false);

  // Sync scrollbar position without jitter so the pinned state remains rock-solid
  const syncScrollToTab = (idx: number) => {
    if (!containerRef.current) return;
    const rect = containerRef.current.getBoundingClientRect();
    const scrollTop = window.pageYOffset || document.documentElement.scrollTop;
    const totalDistance = containerRef.current.offsetHeight - window.innerHeight;
    // Map 4 tabs across 0% to 75% of totalDistance so Tab 3 has a generous static hold phase
    // idx 0 -> 8%, idx 1 -> 30%, idx 2 -> 52%, idx 3 -> 74%
    const targetScroll = scrollTop + rect.top + (0.08 + idx * 0.22) * totalDistance;
    window.scrollTo({ top: targetScroll, behavior: "smooth" });
  };

  // Track native scroll progress (e.g. scrollbar dragging or page scroll)
  const { scrollYProgress } = useScroll({
    target: containerRef,
    offset: ["start start", "end end"]
  });

  useMotionValueEvent(scrollYProgress, "change", (latest) => {
    if (isTransitioningRef.current) return;
    // 0.0 to 0.20 -> Tab 0
    // 0.20 to 0.42 -> Tab 1
    // 0.42 to 0.64 -> Tab 2
    // 0.64 to 0.88 -> Tab 3 (Static hold on Tab 3!)
    // 0.88 to 1.00 -> unpins and smoothly reveals dpoCard
    let nextIdx = 0;
    if (latest >= 0.64) {
      nextIdx = 3;
    } else if (latest >= 0.42) {
      nextIdx = 2;
    } else if (latest >= 0.20) {
      nextIdx = 1;
    } else {
      nextIdx = 0;
    }
    setActiveTabIdx(nextIdx);
  });

  // Direct Wheel Listener: Intercepts mouse wheel while section is pinned to guarantee 100% STATIC viewport
  useEffect(() => {
    const onWheel = (e: WheelEvent) => {
      if (!containerRef.current) return;
      const rect = containerRef.current.getBoundingClientRect();

      // Check if the sticky container is pinned (its top has reached or passed 0, and bottom is still below viewport)
      const isPinned = rect.top <= 25 && rect.bottom >= window.innerHeight - 25;
      if (!isPinned) return; // Allow natural page scroll into / out of the section

      if (Math.abs(e.deltaY) < 18) return; // Ignore micro jitter

      if (e.deltaY > 0) {
        // Scrolling down
        if (activeTabIdx < tabs.length - 1) {
          e.preventDefault(); // LOCK THE PAGE 100% STATIC!
          if (isTransitioningRef.current) return;
          isTransitioningRef.current = true;
          const next = activeTabIdx + 1;
          setActiveTabIdx(next);
          syncScrollToTab(next);
          setTimeout(() => {
            isTransitioningRef.current = false;
          }, 350);
        } else {
          // At Tab 3 (the last tab): all tabs have been shown!
          // Allow natural scroll down to dpoCard & footer!
        }
      } else {
        // Scrolling up
        if (activeTabIdx > 0) {
          e.preventDefault(); // LOCK THE PAGE 100% STATIC!
          if (isTransitioningRef.current) return;
          isTransitioningRef.current = true;
          const prev = activeTabIdx - 1;
          setActiveTabIdx(prev);
          syncScrollToTab(prev);
          setTimeout(() => {
            isTransitioningRef.current = false;
          }, 350);
        } else {
          // At Tab 0: allow natural scroll up to hero!
        }
      }
    };

    window.addEventListener("wheel", onWheel, { passive: false });
    return () => window.removeEventListener("wheel", onWheel);
  }, [activeTabIdx]);

  // Touch listener for mobile trackpads / touch devices
  useEffect(() => {
    let touchStartY = 0;

    const onTouchStart = (e: TouchEvent) => {
      touchStartY = e.touches[0].clientY;
    };

    const onTouchMove = (e: TouchEvent) => {
      if (!containerRef.current) return;
      const rect = containerRef.current.getBoundingClientRect();
      const isPinned = rect.top <= 25 && rect.bottom >= window.innerHeight - 25;
      if (!isPinned) return;

      const touchY = e.touches[0].clientY;
      const deltaY = touchStartY - touchY;

      if (deltaY > 35) {
        if (activeTabIdx < tabs.length - 1) {
          e.preventDefault();
          if (isTransitioningRef.current) return;
          isTransitioningRef.current = true;
          touchStartY = touchY;
          const next = activeTabIdx + 1;
          setActiveTabIdx(next);
          syncScrollToTab(next);
          setTimeout(() => {
            isTransitioningRef.current = false;
          }, 350);
        }
      } else if (deltaY < -35) {
        if (activeTabIdx > 0) {
          e.preventDefault();
          if (isTransitioningRef.current) return;
          isTransitioningRef.current = true;
          touchStartY = touchY;
          const prev = activeTabIdx - 1;
          setActiveTabIdx(prev);
          syncScrollToTab(prev);
          setTimeout(() => {
            isTransitioningRef.current = false;
          }, 350);
        }
      }
    };

    window.addEventListener("touchstart", onTouchStart, { passive: true });
    window.addEventListener("touchmove", onTouchMove, { passive: false });
    return () => {
      window.removeEventListener("touchstart", onTouchStart);
      window.removeEventListener("touchmove", onTouchMove);
    };
  }, [activeTabIdx]);

  const handleTabClick = (idx: number) => {
    setActiveTabIdx(idx);
    syncScrollToTab(idx);
  };

  const filteredCategories = dataCategories.filter(cat => 
    cat.title.toLowerCase().includes(searchQuery.toLowerCase()) ||
    cat.desc.toLowerCase().includes(searchQuery.toLowerCase()) ||
    cat.items.some(item => item.toLowerCase().includes(searchQuery.toLowerCase()))
  );

  const filteredClauses = fullLegalClauses.filter(clause =>
    clause.title.toLowerCase().includes(searchQuery.toLowerCase()) ||
    clause.text.toLowerCase().includes(searchQuery.toLowerCase())
  );

  return (
    <>
      {/* Pinned Scroll Track: 340vh ensures smooth, natural scrolling across the 4 tabs */}
      <div ref={containerRef} className={styles.scrollTrack}>
        
        {/* Sticky Viewport Container: Locks in view while user scrolls */}
        <div className={styles.pinnedContainer}>
          <div className={styles.hubContentBox}>
            
            {/* Top Bar: Live Tabs + Search + Scroll Progress */}
            <div className={styles.tabControlsBar}>
              
              {/* Interactive Tabs with Animated Active Indicator */}
              <div className={styles.tabNav} role="tablist" aria-label="Privacy sections">
                {tabs.map(({ id, label, icon: Icon }, idx) => {
                  const isActive = idx === activeTabIdx;

                  return (
                    <button
                      key={id}
                      type="button"
                      role="tab"
                      aria-selected={isActive}
                      onClick={() => handleTabClick(idx)}
                      className={`${styles.tabBtn} ${isActive ? styles.tabBtnActive : ""}`}
                    >
                      {isActive && (
                        <motion.div
                          layoutId="activePrivacyTabHighlight"
                          className={styles.tabHighlight}
                          transition={{ type: "spring", stiffness: 350, damping: 30 }}
                        />
                      )}
                      <Icon size={15} aria-hidden="true" />
                      <span>{label}</span>
                    </button>
                  );
                })}
              </div>

              {/* Right Side: Step Counter & Quick Search */}
              <div className="flex items-center gap-5 ml-auto">
                <div className={styles.stepIndicator}>
                  <span className={styles.stepNum}>0{activeTabIdx + 1}</span>
                  <div className={styles.stepTrack}>
                    <motion.div
                      className={styles.stepFill}
                      animate={{ width: `${((activeTabIdx + 1) / tabs.length) * 100}%` }}
                      transition={{ type: "spring", stiffness: 340, damping: 30 }}
                    />
                  </div>
                  <span className={styles.scrollHint}>
                    {activeTabIdx < tabs.length - 1 ? (
                      <span className="flex items-center gap-1.5 font-medium text-[#6a3bbd]">
                        Scroll to view {tabs[activeTabIdx + 1].label.split(" (")[0]} <ArrowDown size={11} className="animate-bounce text-[#8763e5]" />
                      </span>
                    ) : (
                      <span className="text-[#059669] font-semibold flex items-center gap-1.5">
                        <CheckCircle2 size={13} className="text-[#059669]" /> All 4 sections viewed · Scroll down to continue <ArrowDown size={11} className="animate-bounce text-[#059669]" />
                      </span>
                    )}
                  </span>
                </div>

                <div className={styles.searchContainer}>
                  <Search size={15} className={styles.searchIcon} aria-hidden="true" />
                  <input
                    type="text"
                    value={searchQuery}
                    onChange={(e) => setSearchQuery(e.target.value)}
                    placeholder="Search topics, DPDP..."
                    className={styles.searchInput}
                    aria-label="Search privacy policy"
                  />
                </div>
              </div>

            </div>

            {/* Tab Content Window: Automatically transitions as activeTabIdx changes */}
            <div className={styles.tabContentStage}>
              <AnimatePresence initial={false}>
                
                {/* TAB 0: Visual Data Flow Pipeline */}
                {activeTabIdx === 0 && (
                  <motion.div
                    key="tab-pipeline"
                    initial={{ opacity: 0, y: 10 }}
                    animate={{ opacity: 1, y: 0 }}
                    exit={{ opacity: 0, y: -10 }}
                    transition={{ duration: 0.2, ease: "easeOut" }}
                    className={styles.pipelineSection}
                  >
                    <div className={styles.pipelineHeader}>
                      <span className={styles.eyebrow}>
                        <span className={styles.liveDot} aria-hidden="true" />
                        Isolated Agent Execution Architecture
                      </span>
                      <h2>How Your Data Flows Through CubeForge Labs</h2>
                      <p>
                        Unlike traditional AI wrappers, CubeForge Labs employs zero-egress sandboxes and cryptographically isolated vector namespaces so your competitive edge never leaks.
                      </p>
                    </div>

                    <div className={styles.pipelineGrid}>
                      {pipelineSteps.map(({ step, title, icon: Icon, tag, tagClass, desc }) => (
                        <div key={step} className={styles.pipelineCard}>
                          <div className={styles.pipelineCardTop}>
                            <span className={styles.pipelineStepNum}>{step}</span>
                            <div className={styles.pipelineIcon}>
                              <Icon size={17} aria-hidden="true" />
                            </div>
                          </div>
                          <h3>{title}</h3>
                          <p>{desc}</p>
                          <span className={`${styles.pipelineTag} ${tagClass}`}>{tag}</span>
                        </div>
                      ))}
                    </div>
                  </motion.div>
                )}

                {/* TAB 1: Collected Data Types & Storage */}
                {activeTabIdx === 1 && (
                  <motion.div
                    key="tab-data"
                    initial={{ opacity: 0, y: 10 }}
                    animate={{ opacity: 1, y: 0 }}
                    exit={{ opacity: 0, y: -10 }}
                    transition={{ duration: 0.2, ease: "easeOut" }}
                    className={styles.categoryGrid}
                  >
                    {filteredCategories.length === 0 ? (
                      <div className="col-span-full py-16 text-center text-[#5b5063]">
                        No privacy categories matched your search term &ldquo;{searchQuery}&rdquo;.
                      </div>
                    ) : (
                      filteredCategories.map(({ title, purpose, icon: Icon, items, retention, desc }) => (
                        <div key={title} className={styles.categoryCard}>
                          <div className={styles.categoryHeader}>
                            <div className={styles.categoryIcon}>
                              <Icon size={20} aria-hidden="true" />
                            </div>
                            <div className={styles.categoryTitleGroup}>
                              <span className={styles.categoryPurpose}>{purpose}</span>
                              <h3>{title}</h3>
                            </div>
                          </div>
                          <p>{desc}</p>

                          <div className={styles.itemChips}>
                            {items.map(item => (
                              <span key={item} className={styles.chip}>{item}</span>
                            ))}
                          </div>

                          <div className={styles.retentionBadge}>
                            <span>Retention</span>
                            <strong>{retention}</strong>
                          </div>
                        </div>
                      ))
                    )}
                  </motion.div>
                )}

                {/* TAB 2: Global Rights & Self-Serve Controls */}
                {activeTabIdx === 2 && (
                  <motion.div
                    key="tab-rights"
                    initial={{ opacity: 0, y: 10 }}
                    animate={{ opacity: 1, y: 0 }}
                    exit={{ opacity: 0, y: -10 }}
                    transition={{ duration: 0.2, ease: "easeOut" }}
                    className={styles.rightsGrid}
                  >
                    {userRights.map(({ title, framework, desc, action, mailSubject }) => (
                      <div key={title} className={styles.rightCard}>
                        <div className={styles.rightCardTop}>
                          <ShieldCheck size={18} aria-hidden="true" />
                          <span className="text-[10px] font-mono font-bold tracking-wider uppercase">{framework}</span>
                        </div>
                        <h3>{title}</h3>
                        <p>{desc}</p>
                        <a
                          href={`mailto:privacy@cubeforgelabs.com?subject=${mailSubject}`}
                          className={styles.rightActionBtn}
                        >
                          <span>{action}</span>
                          <ArrowRight size={14} aria-hidden="true" />
                        </a>
                      </div>
                    ))}
                  </motion.div>
                )}

                {/* TAB 3: Full Legal Clauses */}
                {activeTabIdx === 3 && (
                  <motion.div
                    key="tab-clauses"
                    initial={{ opacity: 0, y: 10 }}
                    animate={{ opacity: 1, y: 0 }}
                    exit={{ opacity: 0, y: -10 }}
                    transition={{ duration: 0.2, ease: "easeOut" }}
                    className={styles.clausesContainer}
                  >
                    {filteredClauses.map(({ num, title, text }) => (
                      <article key={num} className={styles.clauseItem}>
                        <h3>
                          <span>{num}.</span>
                          {title}
                        </h3>
                        <p>{text}</p>
                      </article>
                    ))}
                  </motion.div>
                )}

              </AnimatePresence>
            </div>

          </div>
        </div>
      </div>

      {/* Next Page / Content: Grievance Officer & Statutory DPO Contact Box (reached after scrolling through all tabs) */}
      <div className={styles.dpoCard}>
        <div>
          <h3>Data Protection &amp; Grievance Redressal</h3>
          <p>
            In compliance with India&rsquo;s <strong>Digital Personal Data Protection Act (DPDP Act 2023)</strong> and the <strong>EU General Data Protection Regulation (GDPR)</strong>, our designated Data Protection Officer (DPO) and Grievance Officer reviews all inquiries, access requests, and compliance audits directly.
          </p>
        </div>

        <div className={styles.dpoDetails}>
          <strong>Grievance &amp; Data Protection Officer</strong><br />
          CubeForgeLabs Private Limited<br />
          No 61, 3rd Floor, Industrial Estate, Perungudi,<br />
          Chennai, Tamil Nadu 600096, India<br />
          Direct Inquiries: <a href="mailto:privacy@cubeforgelabs.com">privacy@cubeforgelabs.com</a>
        </div>
      </div>
    </>
  );
}
